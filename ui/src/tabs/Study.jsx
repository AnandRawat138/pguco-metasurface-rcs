import React, { useState } from "react";
import { get, post } from "../api.js";
import { Badge, Button, Card, Empty, ErrorBox, Field, Json, NeedSession, Plot, Stat, Table, fmt, inputCls, seriesColors, useAction, useFetch } from "../components.jsx";

export function Dashboard({ sid, st, refresh, open, go }) {
  const sessions = useFetch(() => get("/sessions"), [sid]);
  const configs = useFetch(() => get("/configs"), []);
  const [cfg, setCfg] = useState("configs/experiments/demo_checkerboard.yaml");
  const act = useAction();
  const create = () => act.run(async () => {
    const r = await post("/sessions", { config_path: cfg });
    open(r.id);
    sessions.reload();
  });
  const C = seriesColors();
  const hist = st?.history || [];
  const improvement = st?.baseline && st?.best_validated ? st.baseline.composite - st.best_validated.composite : null;

  return (
    <div className="grid gap-4">
      <div className="grid gap-4 md:grid-cols-[2fr_1fr]">
        <Card title="Studies" subtitle="One study = one existing design, its objectives and its optimisation history.">
          <div className="flex flex-wrap items-end gap-2 mb-3">
            <Field label="Experiment configuration">
              <select className={inputCls} value={cfg} onChange={(e) => setCfg(e.target.value)}>
                {(configs.data || [cfg]).map((c) => <option key={c}>{c}</option>)}
              </select>
            </Field>
            <div className="mb-2"><Button onClick={create} busy={act.busy}>New study</Button></div>
          </div>
          <ErrorBox error={act.error || sessions.error} />
          <Table
            columns={[
              { label: "Study", render: (r) => <span className="font-mono">{r.id}</span> },
              { label: "Name", key: "name" },
              { label: "State", key: "state" },
              { label: "Created", render: (r) => new Date(r.created * 1000).toLocaleString() },
              { label: "", render: (r) => (r.id === sid ? <span className="text-xs text-accent">open</span> : <button className="text-xs text-accent underline" onClick={() => open(r.id)}>open</button>) },
            ]}
            rows={sessions.data}
          />
        </Card>
        <Card title="Workflow">
          <ol className="text-sm text-ink2 list-decimal pl-5 space-y-1">
            <li>Define the existing design (<button className="text-accent underline" onClick={() => go("Geometry")}>Geometry</button>).</li>
            <li>Load its response y0 (<button className="text-accent underline" onClick={() => go("EM Response")}>EM Response</button>).</li>
            <li>Run the initial design and sensitivity (<button className="text-accent underline" onClick={() => go("Optimization")}>Optimization</button>).</li>
            <li>Validate proposed counterfactuals in HFSS/CST and upload results (<button className="text-accent underline" onClick={() => go("Dataset")}>Dataset</button>).</li>
            <li>Compare and export (<button className="text-accent underline" onClick={() => go("Results")}>Results</button>, <button className="text-accent underline" onClick={() => go("Export")}>Export</button>).</li>
          </ol>
          <p className="text-xs text-muted mt-3">Model outputs are always labeled PREDICTED. No HFSS or CST result is ever generated by this software; the demo uses a labeled synthetic analytic oracle.</p>
        </Card>
      </div>

      <NeedSession session={sid}>
        <div className="grid gap-4 grid-cols-2 lg:grid-cols-4">
          <Stat label="High-fidelity evaluations" value={st?.n_hf ?? 0} sub={st?.budget ? `of budget ${st.budget}` : ""} />
          <Stat label="Baseline composite J(x0)" value={fmt(st?.baseline?.composite)} badge={st?.baseline && <Badge fidelity={st.baseline.label} />} sub="lower is better; 0 by construction under baseline-relative normalisation" />
          <Stat label="Best evaluated composite" value={fmt(st?.best_validated?.composite)} badge={st?.best_validated && <Badge fidelity={st.best_validated.label} />} />
          <Stat label="Improvement over baseline" value={improvement === null ? "–" : fmt(improvement)} sub="composite units (evaluated designs only)" />
        </div>
        <Card title="Convergence" subtitle="Best evaluated composite after each batch. Values come from evaluated designs, never from predictions.">
          {hist.length ? (
            <Plot
              data={[
                { x: hist.map((h) => h.n_hf), y: hist.map((h) => h.best_composite), mode: "lines+markers", name: "best evaluated", line: { color: C[1], width: 2 }, marker: { size: 8 } },
                ...(st?.baseline ? [{ x: [hist[0].n_hf, hist[hist.length - 1].n_hf], y: [st.baseline.composite, st.baseline.composite], mode: "lines", name: "baseline x0", line: { color: C[0], width: 2, dash: "dot" } }] : []),
              ]}
              layout={{ xaxis: { title: "high-fidelity evaluations" }, yaxis: { title: "composite J" } }}
            />
          ) : <Empty>No completed batches yet.</Empty>}
        </Card>
      </NeedSession>
    </div>
  );
}

const FIDELITIES = ["VALIDATED_SIMULATION", "MEASURED", "REPORTED", "REPORTED_PLOT_DIGITIZED"];

function UploadRow({ sid, d, onDone }) {
  const [fid, setFid] = useState("VALIDATED_SIMULATION");
  const [sp, setSp] = useState(null);
  const [rcs, setRcs] = useState(null);
  const [unit, setUnit] = useState("ghz");
  const act = useAction();
  const send = () => act.run(async () => {
    await post(`/sessions/${sid}/results`, { index: d.index, fidelity: fid, sparams: sp, rcs, freq_unit: unit });
    onDone();
  });
  return (
    <div className="flex flex-wrap items-center gap-2">
      <select className={`${inputCls} w-auto`} value={fid} onChange={(e) => setFid(e.target.value)}>{FIDELITIES.map((f) => <option key={f}>{f}</option>)}</select>
      <label className="text-xs">S-params <input type="file" className="text-xs" onChange={(e) => setSp(e.target.files[0])} /></label>
      <label className="text-xs">RCS <input type="file" className="text-xs" onChange={(e) => setRcs(e.target.files[0])} /></label>
      <select className={`${inputCls} w-auto`} value={unit} onChange={(e) => setUnit(e.target.value)}>{["ghz", "mhz", "hz"].map((u) => <option key={u}>{u}</option>)}</select>
      <Button kind="secondary" onClick={send} busy={act.busy} disabled={!sp && !rcs}>Upload</Button>
      <ErrorBox error={act.error} />
    </div>
  );
}

export function Dataset({ sid, st, refresh }) {
  const names = st?.objective_names || [];
  return (
    <NeedSession session={sid}>
      <div className="grid gap-4">
        <Card title="Pending designs" subtitle="Simulate each design in HFSS/CST and upload its Touchstone (.sNp) or CSV result. Declare the fidelity honestly.">
          {st?.pending?.filter((d) => !d.done).length ? (
            <Table
              columns={[
                { label: "#", key: "index" },
                { label: "Tag", key: "tag" },
                { label: "Parameters", render: (d) => <span className="font-mono">{Object.entries(d.values).map(([k, v]) => `${k}=${fmt(v, 3)}`).join("  ")}</span> },
                { label: "Upload result", render: (d) => <UploadRow sid={sid} d={d} onDone={refresh} /> },
              ]}
              rows={st.pending.filter((d) => !d.done)}
            />
          ) : <Empty>No pending designs.</Empty>}
        </Card>
        <Card title="Evaluated designs" subtitle="Training partition: only high-fidelity (or labeled oracle) results. Predictions never enter the training set.">
          <Table
            columns={[
              { label: "Tag", key: "tag" },
              { label: "Fidelity", render: (r) => <Badge fidelity={r.fidelity} /> },
              { label: "Composite", render: (r) => fmt(r.composite) },
              ...names.map((n, i) => ({ label: n, render: (r) => fmt(r.J[i]) })),
              { label: "Pareto", render: (r) => (r.pareto ? "yes" : "") },
            ]}
            rows={st?.records}
          />
        </Card>
      </div>
    </NeedSession>
  );
}

export function ExperimentLog({ sid, st }) {
  const exps = useFetch(() => get("/experiments"), []);
  const [sel, setSel] = useState(null);
  const detail = useFetch(() => (sel ? get(`/experiments/${sel}`) : Promise.resolve(null)), [sel]);
  return (
    <div className="grid gap-4 lg:grid-cols-2">
      <Card title="Recorded experiments" subtitle="Each export writes a reproducibility record (seed, schema, objectives, optimiser, data version, timings) to SQLite.">
        <ErrorBox error={exps.error} />
        <Table
          columns={[
            { label: "Experiment", render: (r) => <button className="text-accent underline font-mono" onClick={() => setSel(r.experiment_id)}>{r.experiment_id}</button> },
            { label: "Name", key: "name" },
            { label: "Seed", key: "seed" },
            { label: "Optimizer", key: "optimizer" },
            { label: "N_HF", key: "n_hf" },
            { label: "Best composite", render: (r) => fmt(r.best_composite) },
          ]}
          rows={exps.data}
        />
      </Card>
      <Card title={sel ? `Record ${sel}` : "Study activity"}>
        {sel ? (detail.data ? <Json value={detail.data} /> : <Empty>Loading…</Empty>) : (
          <NeedSession session={sid}>
            <ul className="text-xs space-y-1">
              {(st?.status?.log || []).slice().reverse().map((l, i) => (
                <li key={i}><span className="text-muted">{new Date(l.t * 1000).toLocaleString()}</span> {l.msg}</li>
              ))}
            </ul>
            {st?.status?.error && <ErrorBox error={st.status.error} />}
          </NeedSession>
        )}
      </Card>
    </div>
  );
}

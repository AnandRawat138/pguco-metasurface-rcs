"""Builds the self-contained ``run_hfss.py`` from the two runner sources.

The script is identical for every job of a given framework version: all job
specifics live in the package's JSON files, which the script reads as data.
That is what lets the worker refuse arbitrary code: it rebuilds this script
itself and only runs a job whose ``run_hfss.py`` is byte-identical.
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_SKIP = re.compile(r"# ---- INLINE-SKIP-BEGIN ----.*?# ---- INLINE-SKIP-END ----\n", re.S)

HEADER = '''#!/usr/bin/env python
"""run_hfss.py - generated by metasurface_optimizer (two-PC HFSS automation, runner {version}).

Self-contained: needs only Python + PyAEDT on the HFSS PC. It reads job.json,
parameters.json, simulation_config.json and template.json from its own folder,
opens the VERIFIED template project, sets the mapped variables, checks every
configuration step, solves, extracts and writes the result package.

Usage (by hand):   python run_hfss.py [--out result_folder] [--graphical]
Usually started by: python hfss_worker/worker.py --input <batch folder>

DO NOT EDIT: the worker runs a job only if this file is byte-identical to its own copy.
"""
'''

RUNNER_VERSION = "1.0.0"


def build_run_hfss_script() -> str:
    compat = (_HERE / "version_compatibility.py").read_text(encoding="utf-8")
    core = _SKIP.sub("", (_HERE / "runner_core.py").read_text(encoding="utf-8"))
    return (HEADER.format(version=RUNNER_VERSION) + "\n" + compat + "\n\n" + core
            + '\n\nif __name__ == "__main__":\n    sys.exit(main())\n')


def trusted_script_sha256() -> str:
    return hashlib.sha256(build_run_hfss_script().encode("utf-8")).hexdigest()
